<?php

namespace App\Console\Commands;

use App\Models\ExpenseCategory;
use Illuminate\Console\Command;

class ExportCategorySeeder extends Command
{
    protected $signature = 'categories:export-seeder';

    protected $description = 'Writes database/seeders/ExpenseCategorySeeder.php from the categories currently in this database, so a fresh clone gets the same set.';

    public function handle()
    {
        $rows = ExpenseCategory::orderBy('id')->get()->map(fn ($c) => [
            'name'        => $c->name,
            'description' => $c->description,
            'icon'        => $c->icon,
            'color'       => $c->color,
            'status'      => $c->status,
            'keywords'    => $c->keywords,
            'is_fallback' => (bool) $c->is_fallback,
        ])->all();

        if (empty($rows)) {
            $this->error('No categories found in this database. Nothing to export.');

            return 1;
        }

        if (!collect($rows)->contains('is_fallback', true)) {
            $this->warn('No catch-all ("Other") category is flagged as the fallback. Receipt scanning will fall back to the first category alphabetically. Create one in Admin > Expense Categories and re-run this command.');
        }

        if (!collect($rows)->contains(fn ($row) => stripos($row['name'], 'savings') !== false)) {
            $this->warn('No "Savings" category found. It is created automatically on the first goal contribution, but with a default icon and color.');
        }

        $template = <<<'PHP'
<?php

namespace Database\Seeders;

use App\Models\ExpenseCategory;
use Illuminate\Database\Seeder;

/**
 * Generated by `php artisan categories:export-seeder`.
 *
 * firstOrCreate() means re-running the seeder never overwrites edits an admin
 * made to a category after the first seed.
 */
class ExpenseCategorySeeder extends Seeder
{
    public function run()
    {
        $categories = __CATEGORIES__;

        foreach ($categories as $data) {
            ExpenseCategory::firstOrCreate(['name' => $data['name']], $data);
        }
    }
}

PHP;

        $path = database_path('seeders/ExpenseCategorySeeder.php');

        if (!is_dir(dirname($path))) {
            $this->error('database/seeders does not exist. This project may still use database/seeds (Laravel 7 layout).');

            return 1;
        }

        file_put_contents($path, str_replace('__CATEGORIES__', var_export($rows, true), $template));

        $this->info('Exported ' . count($rows) . ' categories to database/seeders/ExpenseCategorySeeder.php');

        return 0;
    }
}